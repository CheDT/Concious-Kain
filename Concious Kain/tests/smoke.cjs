const assert = require('node:assert/strict');
const { mkdir, writeFile } = require('node:fs/promises');
const playwright = require(process.argv[2] || 'playwright');
const checks = [];
const record = text => checks.push(text);
(async () => {
  const browser = await playwright.chromium.launch({ headless: true, executablePath: process.env.BROWSER_PATH || (process.platform === 'win32' ? 'C:/Program Files/Google/Chrome/Application/chrome.exe' : undefined) });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [];
  page.setDefaultTimeout(6000);
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
  const base = process.env.APP_URL || 'http://localhost:4173';
  const click = async (name, scope = page) => scope.getByRole('button', { name, exact: true }).click();
  const closed = () => page.waitForFunction(() => !document.querySelector('#app-dialog').open);
  const nav = name => click(name, page.locator('#tab-bar'));
  try {
    await page.goto(base);
    await page.evaluate(() => localStorage.clear());
    await page.reload();
    await page.waitForLoadState('networkidle');
    assert.equal(await page.locator('.food-card').count(), 8);
    await page.locator('.food-card img').evaluateAll(images => Promise.all(images.map(image => { image.loading = 'eager'; return image.decode(); })));
    await mkdir('.qa', { recursive: true });
    await page.screenshot({ path: '.qa/home-desktop.png' });
    record('Home renders eight locally loaded food photos, with no phone border or separate backdrop.');
    await click('Save Beef Caldereta');
    assert.equal(await page.getByRole('button', { name: 'Save Beef Caldereta', exact: true }).getAttribute('aria-pressed'), 'true');
    await click('View Beef Caldereta');
    assert.equal(await page.locator('dialog').isVisible(), true);
    await click('Add to Cart', page.locator('dialog'));
    await closed();
    assert.equal(await page.locator('.cart-badge').textContent(), '4');
    record('Favorite saves; food-detail sheet opens, adds a meal, and animates closed.');
    await nav('Explore');
    await click('Gulay');
    assert.equal(await page.locator('.food-row').count(), 2);
    await page.getByRole('searchbox', { name: 'Search meals' }).fill('coconut');
    assert.equal(await page.locator('.food-row').count(), 1);
    await page.getByRole('searchbox', { name: 'Search meals' }).fill('nomatch');
    assert.equal(await page.getByRole('heading', { name: 'No meals found' }).count(), 1);
    await click('Show all meals');
    assert.equal(await page.locator('.food-row').count(), 8);
    await click('Filter and sort meals');
    await page.locator('#filter-form [name=sort]').selectOption('price-low');
    await click('Show meals');
    await closed();
    assert.equal(await page.locator('.food-row h3').first().textContent(), 'Crispy Talong');
    record('Categories, ingredient search, empty results, clearing filters, and price sorting work.');
    await nav('Home');
    await page.locator('.delivery-bar').click();
    await click('Add a new address');
    await click('Save address');
    assert.equal(await page.locator('#delivery-form [aria-invalid=true]').count(), 3);
    await page.locator('#delivery-form [name=street]').fill('12 Sample Street');
    await page.locator('#delivery-form [name=barangay]').fill('Sample Barangay');
    await page.locator('#delivery-form [name=city]').fill('Quezon City');
    await click('Save address');
    await closed();
    assert.match(await page.locator('.delivery-bar').textContent(), /12 Sample Street/);
    await page.locator('.delivery-bar').click();
    assert.equal(await page.locator('.saved-address.selected').count(), 1);
    await page.locator('.address-choice').click();
    await closed();
    await page.locator('.delivery-bar').click();
    await page.keyboard.press('Escape');
    await closed();
    record('Address sheet validates missing fields, saves a Home address, selects it, and closes with Escape.');
    await page.locator('.cart-button').click();
    await click('Increase Beef Caldereta');
    assert.equal(await page.locator('.cart-badge').textContent(), '5');
    await click('Decrease Beef Caldereta');
    assert.equal(await page.locator('.cart-badge').textContent(), '4');
    await page.getByRole('textbox', { name: 'Promo code' }).fill('bad');
    await click('Apply');
    assert.match(await page.locator('#promo-feedback').textContent(), /isn’t available/);
    await page.getByRole('textbox', { name: 'Promo code' }).fill('kain10');
    await click('Apply');
    assert.equal(await page.locator('.summary-line.discount').count(), 1);
    await page.screenshot({ path: '.qa/cart-desktop.png' });
    record('Cart increase/decrease updates totals; invalid promo shows feedback; KAIN10 applies a discount.');
    await click('Proceed to Checkout');
    await click('Place Order');
    assert.equal(await page.locator('#name[aria-invalid=true]').count(), 1);
    await page.locator('#name').fill('Sample Customer');
    await page.locator('#phone').fill('123');
    await click('Place Order');
    assert.equal(await page.locator('#phone[aria-invalid=true]').count(), 1);
    await click('Autofill');
    assert.equal(await page.locator('#phone').inputValue(), '09000000000');
    await page.locator('[name=payment][value=gcash]').check();
    assert.equal(await page.locator('.gcash-logo').evaluate(image => image.complete && image.naturalWidth > 0), true);
    assert.equal(await page.locator('#checkout-form button[type=submit]').textContent(), 'Place Order');
    assert.equal(await page.locator('#payment-note').count(), 0);
    await page.locator('#app-content').evaluate(element => element.scrollTop = element.scrollHeight);
    await page.screenshot({ path: '.qa/checkout-desktop.png' });
    await click('Place Order');
    assert.equal(await page.getByRole('heading', { name: 'Order placed!', exact: true }).count(), 1);
    assert.match(await page.locator('.order-detail').textContent(), /GCash/);
    await click('View My Orders');
    assert.equal(await page.locator('.order-card').count(), 1);
    await click('View order');
    assert.match(await page.locator('dialog .order-detail').textContent(), /Sample Street/);
    await click('Close dialog');
    await closed();
    await page.reload();
    await nav('Orders');
    assert.equal(await page.locator('.order-card').count(), 1);
    record('Checkout validates name/phone, autofills editable fields, accepts GCash, places an order, and persists its receipt after reload.');
    await nav('Home');
    await click('Add Beef Caldereta to cart');
    await page.locator('.cart-button').click();
    await click('Proceed to Checkout');
    await click('Pickup');
    assert.equal(await page.locator('#street').count(), 0);
    assert.match(await page.locator('.summary').textContent(), /PickupFree/);
    await page.locator('[name=payment][value=cod]').check();
    await click('Place Order');
    assert.match(await page.locator('.order-detail').textContent(), /Cash at pickup/);
    record('Pickup removes address requirements and delivery fees; cash pickup creates the correct receipt.');
    await nav('Profile');
    await page.locator('[data-action=saved]').click();
    assert.equal(await page.locator('.food-row').count(), 1);
    await nav('Profile');
    await click('Settings');
    await click('About Conscious Kain');
    assert.equal(await page.getByRole('heading', { name: 'Conscious Kain', exact: true }).count(), 1);
    await click('Close dialog');
    await closed();
    await click('Settings');
    await click('Reset app data');
    await click('Keep my data');
    await closed();
    await click('Settings');
    await click('Reset app data');
    await click('Reset app data', page.locator('dialog'));
    await closed();
    assert.equal(await page.locator('.cart-badge').textContent(), '3');
    record('Saved meals, profile, settings, about, cancel reset, and confirm reset work.');
    for (const viewport of [{ width: 390, height: 844 }, { width: 320, height: 740 }, { width: 768, height: 1024 }, { width: 1440, height: 900 }]) {
      await page.setViewportSize(viewport);
      await nav('Home');
      await page.waitForTimeout(420);
      const bounds = await page.evaluate(() => ({ overflow: document.documentElement.scrollWidth > innerWidth, appOverflow: document.querySelector('#app-content').scrollWidth > document.querySelector('#app-content').clientWidth, width: document.querySelector('.device').getBoundingClientRect().width, height: document.querySelector('.device').getBoundingClientRect().height }));
      assert.equal(bounds.overflow, false);
      assert.equal(bounds.appOverflow, false);
      if (viewport.width <= 500) assert.equal(bounds.width, viewport.width);
      else assert.ok(Math.abs(bounds.height / bounds.width - 2) < .01);
      await page.locator('.cart-button').click();
      await page.waitForTimeout(420);
      assert.equal(await page.evaluate(() => document.querySelector('#app-content').scrollWidth > document.querySelector('#app-content').clientWidth), false);
      if (viewport.width === 390) await page.screenshot({ path: '.qa/cart-mobile.png' });
    }
    record('320px and 390px phone views fill the screen without overflow; tablet and desktop preserve the 1:2 ratio.');
    await page.setViewportSize({ width: 390, height: 844 });
    await nav('Home');
    await page.waitForLoadState('networkidle');
    await page.waitForTimeout(420);
    await page.screenshot({ path: '.qa/home-mobile.png' });
    await page.locator('.delivery-bar').click();
    const sheet = await page.locator('dialog').boundingBox();
    assert.ok(sheet.x >= 0 && sheet.x + sheet.width <= 390);
    assert.equal(await page.locator('dialog').evaluate(element => getComputedStyle(element).animationName), 'sheet-appear');
    await page.waitForTimeout(500);
    await page.screenshot({ path: '.qa/address-mobile.png' });
    await page.emulateMedia({ reducedMotion: 'reduce' });
    assert.equal(await page.locator('dialog').evaluate(element => getComputedStyle(element).animationName), 'none');
    await page.keyboard.press('Escape');
    await closed();
    record('Mobile sheets fit the screen, animate on open/close, and respect reduced motion.');
    await page.locator('.cart-button').click();
    for (const name of ['Beef Caldereta', 'Talong Adobo', 'Tortang Talong']) await click(`Remove ${name}`);
    assert.equal(await page.getByRole('heading', { name: 'Your cart is empty' }).count(), 1);
    await click('Find a meal');
    await click('All');
    await click('Add Beef Caldereta to cart');
    await page.locator('.cart-button').click();
    await page.getByRole('textbox', { name: 'Promo code' }).fill('KAIN10');
    await click('Apply');
    await page.getByRole('textbox', { name: 'Promo code' }).fill('');
    await click('Apply');
    assert.equal(await page.locator('.summary-line.discount').count(), 0);
    record('Removing the last meal shows the empty cart; browsing refills it; clearing a promo removes the discount.');
    assert.equal((await page.request.get(`${base}/connect.html`)).status(), 404);
    record('The unwanted browser QR page has been removed.');
    assert.deepEqual(errors, []);
    record('No browser console errors or uncaught JavaScript errors across the tested flows.');
    await writeFile('.qa/verification.json', JSON.stringify({ checks, errors }, null, 2));
    console.log(JSON.stringify({ status: 'PASS', checks, errors }, null, 2));
  } catch (error) { console.error(error); await page.screenshot({ path: '.qa/failure.png' }); process.exitCode = 1; }
  finally { await browser.close(); }
})();
